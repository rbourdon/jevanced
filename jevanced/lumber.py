REACH = 2  # tiles: how far from a tree you can chop it
BANK_WIDTH, BANK_HEIGHT = 4, 3


def is_tree(tile_id):
    return tile_id in TREE_TILES


def bank(map_id, x, y):
    """The wood bank a tree tile draws from."""
    return (map_id, x // BANK_WIDTH, y // BANK_HEIGHT)
